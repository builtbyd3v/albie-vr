APP = '''"""Small standard-library tip calculator used by Albie's scripted demo."""
import argparse
from decimal import Decimal, ROUND_HALF_UP


def calculate(bill, percent=15, people=1):
    bill, percent = Decimal(str(bill)), Decimal(str(percent))
    if not bill.is_finite() or not percent.is_finite() or bill < 0 or percent < 0 or people < 1:
        raise ValueError("Bill and percentage must be finite and nonnegative; people must be positive.")
    cents = Decimal("0.01")
    tip = (bill * percent / 100).quantize(cents, rounding=ROUND_HALF_UP)
    total = (bill + tip).quantize(cents, rounding=ROUND_HALF_UP)
    return tip, total, (total / people).quantize(cents, rounding=ROUND_HALF_UP)


def main():
    parser = argparse.ArgumentParser(description="Calculate a tip and split the total.")
    parser.add_argument("bill", type=Decimal)
    parser.add_argument("--percent", type=Decimal, default=Decimal("15"))
    parser.add_argument("--people", type=int, default=1)
    args = parser.parse_args()
    try:
        tip, total, share = calculate(args.bill, args.percent, args.people)
    except ValueError as error:
        parser.error(str(error))
    print(f"Tip: {tip:.2f}\\nTotal: {total:.2f}\\nPer person: {share:.2f}")


if __name__ == "__main__":
    main()
'''

TESTS = '''import subprocess
import sys
import unittest
from decimal import Decimal
from tipcalc import calculate


class TipCalculatorTests(unittest.TestCase):
    def test_split(self):
        self.assertEqual(calculate(20, 15, 2), (Decimal("3.00"), Decimal("23.00"), Decimal("11.50")))

    def test_rounding(self):
        self.assertEqual(calculate(20, 15, 3)[2], Decimal("7.67"))

    def test_no_tip(self):
        self.assertEqual(calculate(10, 0)[1], Decimal("10.00"))

    def test_zero_bill(self):
        self.assertEqual(calculate(0)[1], Decimal("0.00"))

    def test_invalid_values(self):
        for values in [(-1, 15, 1), (10, -1, 1), (10, 15, 0), ("NaN", 15, 1), (10, "Infinity", 1)]:
            with self.subTest(values=values), self.assertRaises(ValueError):
                calculate(*values)

    def test_command_line(self):
        result = subprocess.run([sys.executable, "tipcalc.py", "20", "--people", "2"], capture_output=True, text=True)
        self.assertEqual(result.returncode, 0)
        self.assertIn("Per person: 11.50", result.stdout)


if __name__ == "__main__":
    unittest.main()
'''

