async def run_turn(project, text, mode, emit, *, pet_id, control=None, agent=None):
    task_id = "demo-" + pet_id
    await emit(ev.thinking(pet_id))
    await emit(ev.task_started(pet_id, task_id, "Scripted demo: " + pet_id))
    actions = {
        "builder": ("Creating the fixed tip-calculator sample", "tipcalc.py", APP),
        "tester": ("Adding executable calculation and CLI tests", "test_tipcalc.py", TESTS),
        "scribe": ("Writing the demo's run and test instructions", "README.md", README),
    }
    for line in ("Scripted demo: inspecting the local workspace", actions.get(pet_id, ("Checking the sample files",))[0]):
        if control is not None and control.cancelled.is_set():
            return ""
        await emit(ev.task_progress(pet_id, task_id, line))
        await asyncio.sleep(1.5)
    if control is not None and control.cancelled.is_set():
        return ""
    if pet_id in actions:
        _, name, content = actions[pet_id]
        (project.path / name).write_text(content)
        summary = f"Scripted demo: created {name}."
    else:
        if not all((project.path / name).is_file() for name in ("tipcalc.py", "test_tipcalc.py", "README.md")):
            return "Scripted demo: expected sample files are missing. REVIEW: FAIL"
        summary = "Scripted demo: expected sample files are present; independent tests run next. REVIEW: PASS"
